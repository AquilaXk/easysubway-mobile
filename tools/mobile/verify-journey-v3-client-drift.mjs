import { constants, closeSync, fstatSync, lstatSync, openSync, readFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildJourneyV3GenerationForDrift, selectJourneyV3GenerationReceiptForDrift } from './generate-journey-v3-client.mjs';

const fail = (message) => { throw new Error(`verify-journey-v3-client-drift: ${message}`); };

function regular(path, label) {
  if (constants.O_NOFOLLOW === undefined) fail('O_NOFOLLOW is required');
  let fd;
  try {
    fd = openSync(path, constants.O_RDONLY | constants.O_NOFOLLOW);
    if (!fstatSync(fd).isFile()) fail(`${label} must be regular`);
    return readFileSync(fd);
  } catch (error) {
    if (error.message.startsWith('verify-journey-v3-client-drift:')) throw error;
    fail(`${label} must be a regular non-symlink file`);
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

function assertGeneratedRoot(path) {
  const root = resolve(path);
  let stat;
  try { stat = lstatSync(root); } catch { fail('generated root must exist'); }
  if (!stat.isDirectory() || stat.isSymbolicLink()) fail('generated root must be a real non-symlink directory');
  return root;
}

export function verifyJourneyV3ClientDriftForTest({ contractRoot, lockPath, generatedRoot, nodeMajorVersion }) {
  const root = assertGeneratedRoot(generatedRoot);
  const selectedReceipt = selectJourneyV3GenerationReceiptForDrift(regular(join(root, 'journey_v3_generation_receipt.json'), 'generation receipt'));
  const expected = buildJourneyV3GenerationForDrift({ contractRoot, lockPath, nodeMajorVersion });
  const expectedNames = Object.keys(expected.files).sort();
  const actualNames = readdirSync(root).sort();
  if (JSON.stringify(actualNames) !== JSON.stringify(expectedNames)) fail('generated file set differs from the exact closed set');
  for (const name of expectedNames) {
    const path = join(root, name);
    let stat;
    try { stat = lstatSync(path); } catch { fail(`${name} is missing`); }
    if (!stat.isFile() || stat.isSymbolicLink()) fail(`${name} must be a regular non-symlink file`);
    if (!regular(path, name).equals(expected.files[name])) fail(`${name} differs from regenerated bytes`);
  }
  return Object.freeze({ generatedRoot: root, receipt: expected.receipt });
}

function parseArguments(argv) {
  if (argv.length !== 6 || argv[0] !== '--contract-root' || argv[2] !== '--lock' || argv[4] !== '--generated-root') fail('usage is --contract-root <staged> --lock <tracked-lock> --generated-root <tracked-generated-root>');
  return { contractRoot: argv[1], lockPath: argv[3], generatedRoot: argv[5] };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try { verifyJourneyV3ClientDriftForTest(parseArguments(process.argv.slice(2))); }
  catch (error) { process.stderr.write(`${error.message}\n`); process.exitCode = 1; }
}
